#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { repoRoot, seoDatesModulePath, seoDatesReportPath } from './content-paths.mjs';
import { resolveContentDates, validateStagedContent } from './seo-content-history.mjs';
import { applySharedContentReleases } from './seo-content-releases.mjs';

export function strictSeoEnvironment(env = process.env) {
  return (Boolean(env.CI) && env.CI !== 'false') || env.VERCEL === '1'
    || ['preview', 'production'].includes(env.VERCEL_ENV);
}

export function contentDateFiles(report) {
  const dates = Object.fromEntries(Object.entries(report.routes).sort(([a], [b]) => a.localeCompare(b))
    .filter(([, entry]) => entry.lastmod).map(([route, entry]) => [route, entry.lastmod]));
  return new Map([
    [seoDatesReportPath, `${JSON.stringify(report, null, 2)}\n`],
    [seoDatesModulePath, '// Generated by scripts/generate-seo-content-dates.mjs. Do not edit.\n'
      + `export const SEO_CONTENT_DATES: Readonly<Record<string, string>> = ${JSON.stringify(dates, null, 2)};\n`],
  ]);
}

export function verifyOrWriteFiles(files, { check = false } = {}) {
  const stale = [];
  for (const [file, text] of files) {
    const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (previous === text) continue;
    if (check) stale.push(path.relative(repoRoot, file));
    else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text, 'utf8');
    }
  }
  if (stale.length) throw new Error(`Stale or missing SEO artifacts. Run npm run gen:seo:\n${stale.join('\n')}`);
}

export async function generateContentDates({ check = false, staged = false, strict = strictSeoEnvironment() } = {}) {
  const report = staged ? validateStagedContent({ repoRoot })
    : applySharedContentReleases(await resolveContentDates({ repoRoot, mode: strict ? 'strict' : 'local', snapshot: 'worktree' }));
  if (!staged) verifyOrWriteFiles(contentDateFiles(report), { check });
  console.log(`[seo:dates] revision=${report.revision.slice(0, 12)} routes=${Object.keys(report.routes).length}`
    + ` pending=${report.pending.length} unresolved=${report.unresolved.length}`);
  for (const route of report.pending) console.log(`[seo:dates] pending (no published lastmod): ${route}`);
  for (const issue of report.unresolved) console.log(`[seo:dates] unresolved: ${typeof issue === 'string' ? issue : JSON.stringify(issue)}`);
  return report;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  generateContentDates({ check: process.argv.includes('--check'), staged: process.argv.includes('--staged'),
    strict: process.argv.includes('--strict') || strictSeoEnvironment() })
    .catch((error) => { console.error(`[seo:dates] ${error.message}`); process.exitCode = 1; });
}
