import { shouldIncludeRegistryDetailInSitemap } from './registry-detail-access-policy.mjs';

export function buildPublicQuestionNavigation(registry) {
  const routes = new Set();
  return registry.flatMap((entry) => {
    const match = /^\/(javascript|react|angular|vue|html|css)\/(coding|trivia|debug)\/[^/]+$/.exec(entry.route || '');
    if (entry.family !== 'question' || !match || !shouldIncludeRegistryDetailInSitemap(entry.route, entry.access)) {
      return [];
    }
    if (routes.has(entry.route)) throw new Error(`Duplicate public question route: ${entry.route}`);
    routes.add(entry.route);
    return [{ tech: match[1], kind: match[2], title: entry.title, route: entry.route }];
  }).sort((a, b) => a.tech.localeCompare(b.tech, 'en')
    || a.kind.localeCompare(b.kind, 'en')
    || a.title.localeCompare(b.title, 'en')
    || a.route.localeCompare(b.route, 'en'));
}

export function publicQuestionNavigationText(entries) {
  return `// Auto-generated by scripts/generate-practice-registry.mjs. Do not edit by hand.
export type PublicQuestionNavigationItem = {
  tech: 'javascript' | 'react' | 'angular' | 'vue' | 'html' | 'css';
  kind: 'coding' | 'trivia' | 'debug';
  title: string;
  route: string;
};

export const PUBLIC_QUESTION_NAVIGATION: readonly PublicQuestionNavigationItem[] = ${JSON.stringify(entries, null, 2)};
`;
}
