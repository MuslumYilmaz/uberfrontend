#!/usr/bin/env node
// Vendors the Vue files the framework preview loads, from the npm registry: vue.global.js (the development build, so
// Vue's warnings reach the preview console) and @vue/compiler-sfc, whose only browser build is an ES module.
// The preview runs in a sandboxed iframe with an opaque origin, where a module script from the site needs CORS
// headers that local servers do not send, so the compiler is rewritten into a classic script that sets
// self.VueCompilerSFC. vue.global.prod.js stays: the content regression tests run it.
//
//   node scripts/vendor-vue-preview.mjs [version]   download, verify integrity, write the files
//   node scripts/vendor-vue-preview.mjs --check     every vendored Vue file carries the same version
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '3.5.26';
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vendorDir = path.join(projectRoot, 'src', 'assets', 'vendor', 'vue');
const FILES = {
  prod: path.join(vendorDir, 'vue.global.prod.js'),
  dev: path.join(vendorDir, 'vue.global.js'),
  compiler: path.join(vendorDir, 'compiler-sfc.global.js'),
};

function bannerVersion(file, name) {
  const head = fs.readFileSync(file, 'utf8').slice(0, 300);
  return head.match(new RegExp(`${name.replace(/[/@]/g, '\\$&')} v(\\d+\\.\\d+\\.\\d+)`))?.[1] ?? null;
}

function check() {
  const problems = [];
  const versions = {
    prod: bannerVersion(FILES.prod, 'vue'),
    dev: bannerVersion(FILES.dev, 'vue'),
    compiler: bannerVersion(FILES.compiler, '@vue/compiler-sfc'),
  };
  for (const [key, version] of Object.entries(versions)) {
    if (version !== VERSION) problems.push(`${path.relative(projectRoot, FILES[key])}: version ${version ?? 'missing'}, expected ${VERSION}`);
  }
  const compiler = fs.readFileSync(FILES.compiler, 'utf8');
  if (!compiler.includes('self.VueCompilerSFC = {')) problems.push('compiler-sfc.global.js does not set self.VueCompilerSFC');
  if (/\nexport \{[^}]*\};\s*$/.test(compiler)) problems.push('compiler-sfc.global.js still ends with a module export');
  if (problems.length) {
    console.error(`[vendor-vue-preview] ${problems.join('\n[vendor-vue-preview] ')}`);
    process.exit(1);
  }
  console.log(`[vendor-vue-preview] check passed: vue ${VERSION} (prod, dev) and @vue/compiler-sfc ${VERSION}`);
}

/** The ES module build has one export statement at its end; everything else runs unchanged inside a function. */
function toClassicScript(esm) {
  const exportStatement = /\nexport \{([^}]*)\};\s*$/;
  const match = esm.match(exportStatement);
  if (!match) throw new Error('compiler-sfc.esm-browser.js no longer ends with one export statement');
  const members = match[1].split(',').map((part) => part.trim()).filter(Boolean).map((part) => {
    const [local, exported] = part.split(/\s+as\s+/);
    return exported ? `${exported}: ${local}` : local;
  });
  const banner = esm.match(/^\/\*\*[\s\S]*?\*\*\/\n/)?.[0] ?? '';
  const body = esm.slice(banner.length).replace(exportStatement, '\n');
  return `${banner}// Generated by scripts/vendor-vue-preview.mjs from compiler-sfc.esm-browser.js: a classic script that sets
// self.VueCompilerSFC, so the sandboxed preview loads it without CORS.
(function () {
'use strict';
${body}
self.VueCompilerSFC = { ${members.join(', ')} };
})();
`;
}

function download(version) {
  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), 'vendor-vue-'));
  try {
    const packages = [`vue@${version}`, `@vue/compiler-sfc@${version}`];
    const packed = JSON.parse(execFileSync('npm', ['pack', ...packages, '--json'], { cwd: workDir, encoding: 'utf8' }));
    const extracted = {};
    for (const [index, entry] of packed.entries()) {
      const expected = execFileSync('npm', ['view', packages[index], 'dist.integrity'], { encoding: 'utf8' }).trim();
      const actual = `sha512-${crypto.createHash('sha512').update(fs.readFileSync(path.join(workDir, entry.filename))).digest('base64')}`;
      if (actual !== expected) throw new Error(`${packages[index]}: integrity ${actual} does not match the registry's ${expected}`);
      const target = path.join(workDir, `pkg-${index}`);
      fs.mkdirSync(target);
      execFileSync('tar', ['-xzf', path.join(workDir, entry.filename), '-C', target]);
      extracted[entry.name] = path.join(target, 'package');
    }
    const prod = fs.readFileSync(path.join(extracted.vue, 'dist', 'vue.global.prod.js'));
    if (!prod.equals(fs.readFileSync(FILES.prod))) {
      console.warn('[vendor-vue-preview] vue.global.prod.js differs from the vendored copy; replacing it too');
      fs.writeFileSync(FILES.prod, prod);
    }
    fs.copyFileSync(path.join(extracted.vue, 'dist', 'vue.global.js'), FILES.dev);
    const esm = fs.readFileSync(path.join(extracted['@vue/compiler-sfc'], 'dist', 'compiler-sfc.esm-browser.js'), 'utf8');
    fs.writeFileSync(FILES.compiler, toClassicScript(esm));
    for (const file of Object.values(FILES)) {
      const bytes = fs.readFileSync(file);
      console.log(`[vendor-vue-preview] ${path.relative(projectRoot, file)} ${bytes.length} bytes sha256 ${crypto.createHash('sha256').update(bytes).digest('hex')}`);
    }
  } finally {
    fs.rmSync(workDir, { recursive: true, force: true });
  }
}

if (process.argv.includes('--check')) {
  check();
} else {
  const version = process.argv.slice(2).find((argument) => /^\d+\.\d+\.\d+$/.test(argument)) ?? VERSION;
  if (version !== VERSION) throw new Error(`Update VERSION in this script to ${version} first, so --check follows it.`);
  download(version);
  check();
}
