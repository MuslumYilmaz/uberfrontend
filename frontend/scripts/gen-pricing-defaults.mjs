#!/usr/bin/env node
// Writes src/app/generated/pricing-defaults.ts from the backend plan catalog so the
// prerendered pricing surfaces (the /pricing page and the homepage plan cards) show
// the same prices and the same sprint layout that the checkout config confirms after
// hydration. When the backend source is absent, the committed file is kept.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = path.resolve(frontendRoot, '..', 'backend', 'services', 'billing', 'checkout-start.js');
const outPath = path.join(frontendRoot, 'src', 'app', 'generated', 'pricing-defaults.ts');
const PLAN_IDS = ['monthly', 'quarterly', 'annual', 'lifetime'];
const INTERVALS = new Set(['month', 'year', 'one_time']);

function loadCatalog() {
  if (!fs.existsSync(catalogPath)) return null;
  const { PLAN_CATALOG } = require(catalogPath);
  return PLAN_CATALOG || null;
}

const catalog = loadCatalog();
if (!catalog) {
  if (fs.existsSync(outPath)) {
    console.warn('[gen-pricing-defaults] backend catalog not found; keeping the committed pricing-defaults.ts');
    process.exit(0);
  }
  console.error('[gen-pricing-defaults] backend catalog not found and no generated file exists');
  process.exit(1);
}

const details = {};
for (const planId of PLAN_IDS) {
  const plan = catalog[planId];
  const valid = plan
    && Number.isInteger(plan.amountCents) && plan.amountCents > 0
    && typeof plan.currency === 'string' && plan.currency
    && INTERVALS.has(plan.interval)
    && (plan.intervalCount === null || (Number.isInteger(plan.intervalCount) && plan.intervalCount > 0));
  if (!valid) {
    console.error(`[gen-pricing-defaults] invalid catalog entry for ${planId}`);
    process.exit(1);
  }
  details[planId] = {
    amountCents: plan.amountCents,
    currency: plan.currency,
    interval: plan.interval,
    intervalCount: plan.intervalCount,
    // BILLING_TAX_INCLUSIVE defaults to true on the backend; the config response confirms it after hydration.
    taxInclusive: true,
  };
}

const body = `// Auto-generated by scripts/gen-pricing-defaults.mjs from backend/services/billing/checkout-start.js. Do not edit by hand.
// Prerendered pricing surfaces render these defaults; the live checkout config replaces them after hydration.
export type PrerenderPlanDetail = {
  amountCents: number;
  currency: string;
  interval: 'month' | 'year' | 'one_time';
  intervalCount: number | null;
  taxInclusive: boolean;
};

export const PRERENDER_PLAN_DETAILS: Record<'monthly' | 'quarterly' | 'annual' | 'lifetime', PrerenderPlanDetail> = ${JSON.stringify(details, null, 2)};
`;

const previous = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : null;
if (previous !== body) {
  fs.writeFileSync(outPath, body);
  console.log('[gen-pricing-defaults] wrote src/app/generated/pricing-defaults.ts');
} else {
  console.log('[gen-pricing-defaults] pricing-defaults.ts is current');
}
