import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const PREVIEW_BACKEND_HOST_PREFIX = 'frontendatlas-be-';
const PREVIEW_TEAM_HOST_SUFFIX = '-muslumyilmazs-projects.vercel.app';

function normalizedVercelEnvironment(env) {
  return String(env.VERCEL_ENV || '').trim().toLowerCase();
}

export function normalizePreviewApiBase(rawValue) {
  const raw = String(rawValue || '').trim();
  if (!raw) {
    throw new Error('NG_APP_PREVIEW_API_BASE is required for every Vercel Preview build.');
  }

  let url;
  try {
    url = new URL(raw);
  } catch {
    throw new Error('NG_APP_PREVIEW_API_BASE must be an absolute HTTPS URL.');
  }

  const hostname = url.hostname.toLowerCase();
  if (url.protocol !== 'https:') {
    throw new Error('NG_APP_PREVIEW_API_BASE must use HTTPS.');
  }
  if (url.username || url.password || url.search || url.hash) {
    throw new Error('NG_APP_PREVIEW_API_BASE must not contain credentials, query parameters, or a fragment.');
  }
  if (url.pathname !== '/' && url.pathname !== '') {
    throw new Error('NG_APP_PREVIEW_API_BASE must be an origin without a path.');
  }
  if (
    !hostname.startsWith(PREVIEW_BACKEND_HOST_PREFIX)
    || !hostname.endsWith(PREVIEW_TEAM_HOST_SUFFIX)
  ) {
    throw new Error(
      `NG_APP_PREVIEW_API_BASE must target the FrontendAtlas backend Preview deployment ending in ${PREVIEW_TEAM_HOST_SUFFIX}.`
    );
  }
  if (hostname === 'api.frontendatlas.com' || hostname === 'frontendatlas.com') {
    throw new Error('Production FrontendAtlas origins are forbidden in a Preview build.');
  }

  return url.origin;
}

export function resolveDeploymentConfig(env = process.env) {
  const vercelEnvironment = normalizedVercelEnvironment(env);
  if (vercelEnvironment === 'preview') {
    return {
      environment: 'preview',
      apiBase: normalizePreviewApiBase(env.NG_APP_PREVIEW_API_BASE),
    };
  }
  return {
    environment: vercelEnvironment === 'production' ? 'production' : 'local',
    apiBase: '',
  };
}

export function renderDeploymentConfig(config) {
  const safeConfig = {
    environment: String(config?.environment || 'local'),
    apiBase: String(config?.apiBase || ''),
  };
  const lines = [
    '// Generated by scripts/gen-deployment-env.mjs. This file must never contain secrets.',
    '(function installFrontendAtlasDeploymentConfig(global) {',
    `  var config = Object.freeze(${JSON.stringify(safeConfig)});`,
    "  Object.defineProperty(global, '__FA_DEPLOYMENT_CONFIG__', { value: config, configurable: false, writable: false });",
  ];
  if (safeConfig.apiBase) {
    lines.push(
      "  Object.defineProperty(global, '__FA_API_BASE__', { value: config.apiBase, configurable: false, writable: false });"
    );
  }
  lines.push('})(window);', '');
  return lines.join('\n');
}

export function writeDeploymentConfig({ env = process.env, outputPath } = {}) {
  const resolvedOutputPath = outputPath
    ? path.resolve(outputPath)
    : path.resolve('src/assets/deployment-config.js');
  const config = resolveDeploymentConfig(env);
  fs.writeFileSync(resolvedOutputPath, renderDeploymentConfig(config));
  console.log(
    `[deployment] generated ${config.environment} browser config`
    + (config.apiBase ? ` for ${new URL(config.apiBase).hostname}` : '')
  );
  return config;
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : '';
if (invokedPath === import.meta.url) {
  writeDeploymentConfig();
}
